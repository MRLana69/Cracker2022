namespace Missions;

public abstract class AwardGoal
{
	public int goal
	{
		get
		{
			return field;
		}
		set
		{
			field = value;
		}
	}

	public bool hasIcon
	{
		get
		{
			return field;
		}
		set
		{
			field = value;
		}
	}

	public string iconName
	{
		get
		{
			return field;
		}
		set
		{
			field = value;
		}
	}
}
